// One-line node install: the owner adds a node and gets
//   curl -fsSL https://HUB/install/<token> | bash
// The token works for one hour and only until the node fetched its
// credential. The script verifies every binary against a sha256 the HUB
// computed, so a tampered download is refused.

const installSchema = `
CREATE TABLE IF NOT EXISTS node_installs (
  token_sha256 TEXT PRIMARY KEY,
  node_id TEXT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  node_token TEXT NOT NULL,
  expires_unix INTEGER NOT NULL
);
`

const installTTL = time.Hour

func (s *Store) ensureInstallSchema() error {
	_, err := s.db.Exec(installSchema)
	return err
}

// CreateNodeInstall registers a node and returns its one-time install token.
func (s *Store) CreateNodeInstall(ctx context.Context, id, name string) (installToken string, err error) {
	nodeTok, err := s.CreateNode(ctx, id, name)
	if err != nil {
		return "", err
	}
	installToken = randomHex(24)
	_, err = s.db.ExecContext(ctx, `INSERT INTO node_installs(token_sha256,node_id,node_token,expires_unix) VALUES(?,?,?,?)`,
		hashToken(installToken), id, nodeTok, s.now().Add(installTTL).Unix())
	return installToken, err
}

// NewInstallToken re-issues an install for an existing node (rotating its
// credential, so a lost server can be replaced).
func (s *Store) NewInstallToken(ctx context.Context, id string) (string, error) {
	nodeTok, err := s.RotateNodeToken(ctx, id)
	if err != nil {
		return "", err
	}
	tok := randomHex(24)
	_, err = s.db.ExecContext(ctx, `INSERT INTO node_installs(token_sha256,node_id,node_token,expires_unix) VALUES(?,?,?,?)`,
		hashToken(tok), id, nodeTok, s.now().Add(installTTL).Unix())
	return tok, err
}

func (s *Store) lookupInstall(ctx context.Context, tok string) (nodeID, nodeToken string, err error) {
	err = s.ro.QueryRowContext(ctx, `SELECT node_id,node_token FROM node_installs WHERE token_sha256=? AND expires_unix>=?`,
		hashToken(tok), s.now().Unix()).Scan(&nodeID, &nodeToken)
	if errors.Is(err, sql.ErrNoRows) {
		return "", "", ErrNotFound
	}
	return nodeID, nodeToken, err
}

func (s *Store) consumeInstall(ctx context.Context, tok string) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM node_installs WHERE token_sha256=? OR expires_unix<?`, hashToken(tok), s.now().Unix())
	return err
}

// InstallConfig tells the installer where things are.
type InstallConfig struct {
	DistDir   string // holds dark-node and xray
	PublicURL string // where nodes reach this installer, e.g. https://1.2.3.4:28096
	HubURL    string // node API, e.g. https://1.2.3.4:28443
	CAFile    string // CA that signs the node API certificate
}

func fileSHA(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// InstallHandler serves /install/<token> (the script) and its files.
func InstallHandler(s *Store, cfg InstallConfig) http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /install/{tok}", func(w http.ResponseWriter, r *http.Request) {
		tok := r.PathValue("tok")
		nodeID, _, err := s.lookupInstall(r.Context(), tok)
		if err != nil {
			http.NotFound(w, r)
			return
		}
		nodeSHA, err1 := fileSHA(filepath.Join(cfg.DistDir, "dark-node"))
		xraySHA, err2 := fileSHA(filepath.Join(cfg.DistDir, "xray"))
		if err1 != nil || err2 != nil {
			http.Error(w, "installer files missing on the HUB", http.StatusServiceUnavailable)
			return
		}
		base := strings.TrimRight(cfg.PublicURL, "/") + "/install/" + tok
		w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
		w.Header().Set("Cache-Control", "no-store")
		fmt.Fprintf(w, installScript, nodeID, base, nodeSHA, xraySHA, cfg.HubURL)
	})
	mux.HandleFunc("GET /install/{tok}/{file}", func(w http.ResponseWriter, r *http.Request) {
		tok := r.PathValue("tok")
		_, nodeToken, err := s.lookupInstall(r.Context(), tok)
		if err != nil {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Cache-Control", "no-store")
		switch f := r.PathValue("file"); f {
		case "dark-node", "xray":
			http.ServeFile(w, r, filepath.Join(cfg.DistDir, f))
		case "hub-ca.pem":
			http.ServeFile(w, r, cfg.CAFile)
		case "token":
			// The credential is handed out once; the install link dies with it.
			_, _ = w.Write([]byte(nodeToken))
			_ = s.consumeInstall(r.Context(), tok)
		default:
			http.NotFound(w, r)
		}
	})
	return mux
}

const installScript = `#!/bin/bash
# DARK v2 node installer for node %[1]s. Generated by the HUB; valid once.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "run as root"; exit 1; }
B=%[2]s
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
echo "[dark] downloading..."
curl -fsS -o "$T/dark-node" "$B/dark-node"
curl -fsS -o "$T/xray" "$B/xray"
curl -fsS -o "$T/hub-ca.pem" "$B/hub-ca.pem"
echo "%[3]s  $T/dark-node" | sha256sum -c --quiet -
echo "%[4]s  $T/xray" | sha256sum -c --quiet -
curl -fsS -o "$T/token" "$B/token"
install -d -m 0755 /opt/dark-v2
install -m 0755 "$T/dark-node" /opt/dark-v2/dark-node
install -m 0755 "$T/xray" /opt/dark-v2/xray
install -d -m 0700 /etc/dark-node /var/lib/dark-node
install -m 0600 "$T/token" /etc/dark-node/token
install -m 0600 "$T/hub-ca.pem" /etc/dark-node/hub-ca.pem
printf 'DARK_NODE_HUB=%[5]s\nDARK_NODE_ID=%[1]s\n' > /etc/dark-node/env
cat > /etc/systemd/system/dark-node.service <<'UNIT'
[Unit]
Description=DARK v2 Node (stock Xray supervisor; traffic never waits for the HUB)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
EnvironmentFile=/etc/dark-node/env
ExecStart=/opt/dark-v2/dark-node -hub ${DARK_NODE_HUB} -node-id ${DARK_NODE_ID} -token-file /etc/dark-node/token -hub-ca /etc/dark-node/hub-ca.pem -xray /opt/dark-v2/xray -state /var/lib/dark-node
Restart=always
RestartSec=2
LimitNOFILE=1048576
AmbientCapabilities=CAP_NET_BIND_SERVICE CAP_NET_ADMIN
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=/var/lib/dark-node /opt/dark-v2

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable dark-node.service >/dev/null 2>&1
# restart (not just start): a re-install must pick up the new credential.
systemctl restart dark-node.service
sleep 3
systemctl is-active dark-node.service && echo "[dark] node %[1]s is running"
`
